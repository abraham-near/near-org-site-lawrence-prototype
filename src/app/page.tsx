import type { Metadata } from "next";
import data from "@/versions.json";
import styles from "./versions.module.css";

export const metadata: Metadata = { title: "Versions", robots: { index: false, follow: false } };

type Version = (typeof data.versions)[number] & { tag?: string; options?: { label: string; path: string }[] };

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
// The commit's own wall-clock date and time, as written in versions.json (no time-zone conversion)
const when = (iso: string) => {
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  return { day: `${d} ${MONTHS[m - 1]} ${y}`, time: iso.slice(11, 16) };
};
const byNewest = (a: Version, b: Version) => Date.parse(b.date) - Date.parse(a.date);
const href = (commit: string, sub: string) => `/versions/${commit}${sub ? `/${sub}` : ""}`;

// The site's root while we design (D39): every version of the homepage, newest first, grouped by direction. The
// working copy is live at /home; each committed version opens as its own frozen build under /versions/<commit>
// (public/versions is generated by npm run versions, so a fresh clone needs that run before these links work).
export default function VersionsIndex() {
  const versions = [...(data.versions as Version[])].sort(byNewest);
  const directions = data.directions
    .map((d) => ({ ...d, versions: versions.filter((v) => v.direction === d.key) }))
    .filter((d) => d.versions.length)
    .sort((a, b) => byNewest(a.versions[0], b.versions[0]));
  const { live } = data;

  return (
    <main id="main" className={`container-page ${styles.page}`}>
      <header className={styles.intro}>
        <h1 className="t-h1">Versions</h1>
        <p className="t-lede text-muted">
          Every version of the near.org homepage, newest first. The working copy is live; each committed version opens as it
          was when it was committed.
        </p>
      </header>

      <section className={styles.group} aria-labelledby="live-title">
        <h2 id="live-title" className="t-h3">Now</h2>
        <ol className={styles.list}>
          <li className={styles.row}>
            <p className={styles.when}><span className={styles.live}>Live</span></p>
            <div className={styles.what}>
              <h3 className="t-h4">{live.title}</h3>
              <p className={styles.summary}>{live.summary}</p>
            </div>
            <div className={styles.open}>
              <a className="btn btn-secondary" href={live.home}>Open homepage<span className="sr-only">: {live.title}</span></a>
              <ul className={styles.options}>
                {live.options.map((o) => <li key={o.path}><a href={o.path}>{o.label}<span className="sr-only">: {live.title}</span></a></li>)}
              </ul>
            </div>
          </li>
        </ol>
      </section>

      {directions.map((d) => (
        <section key={d.key} className={styles.group} aria-labelledby={`dir-${d.key}`}>
          <h2 id={`dir-${d.key}`} className="t-h3">{d.name}</h2>
          <p className={styles.note}>{d.note}</p>
          <ol className={styles.list}>
            {d.versions.map((v) => {
              const t = when(v.date);
              const of = <span className="sr-only">: {v.title}, {t.day}</span>;
              return (
                <li key={v.commit} className={styles.row}>
                  <p className={styles.when}>
                    <time dateTime={v.date}>{t.day}<br />{t.time}</time>
                    <span className={styles.commit}>{v.commit}</span>
                    {v.tag && <span className={styles.tag}>Tag {v.tag}</span>}
                  </p>
                  <div className={styles.what}>
                    <h3 className="t-h4">{v.title}</h3>
                    {v.summary.map((s) => <p key={s} className={styles.summary}>{s}</p>)}
                    {v.decisions.length > 0 && <p className={styles.decisions}>{v.decisions.join(", ")}</p>}
                  </div>
                  <div className={styles.open}>
                    <a className="btn btn-secondary" href={href(v.commit, v.home)}>Open homepage{of}</a>
                    {v.options && (
                      <ul className={styles.options}>
                        {v.options.map((o) => <li key={o.path}><a href={href(v.commit, o.path)}>{o.label}{of}</a></li>)}
                      </ul>
                    )}
                  </div>
                </li>
              );
            })}
          </ol>
        </section>
      ))}
    </main>
  );
}
